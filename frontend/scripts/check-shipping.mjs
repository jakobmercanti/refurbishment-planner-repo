import { createRequire } from 'node:module';
import { mkdir, readFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({ channel: 'chrome', headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [], failed = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('response', r => { if (r.status() >= 400) failed.push(`${r.status()} ${r.url()}`); });
  await page.goto(process.env.PREVIEW_ORIGIN || 'http://127.0.0.1:4176/planner-test/');
  await page.getByRole('button', { name: 'Tools', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Tools', exact: true }).click();
  assert.equal(await page.getByRole('button', { name: 'Object catalogue manager…', exact: true }).count(), 0);
  await page.keyboard.press('Escape');
  const events = [];
  await page.route('https://us.i.posthog.com/**', route => { events.push(route.request().postDataJSON()); return route.fulfill({ status: 200, body: '{}' }); });
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await page.getByRole('button', { name: 'Privacy and local saving…', exact: true }).click();
  await page.getByRole('button', { name: 'Allow usage counts', exact: true }).click();
  await page.getByRole('button', { name: 'New outline', exact: true }).click();
  await page.getByRole('button', { name: 'Ok', exact: true }).click();
  await page.waitForTimeout(2500);
  const roomName = page.locator('input[aria-label^="Name "]').first();
  await roomName.fill('Release test room');
  await page.waitForTimeout(1800);
  assert.equal(await roomName.inputValue(), 'Release test room');
  console.log('After room creation:', await page.getByRole('status').allTextContents());
  await page.getByRole('button', { name: 'Tools', exact: true }).click();
  await page.getByRole('button', { name: 'My 3D models…', exact: true }).click();
  // Minimal self-contained triangle mesh with nonzero bounds on every axis.
  const mesh = new Float32Array([0,0,0, 1,0,1, 0,1,0]);
  const metadata = { asset: { version: '2.0' }, buffers: [{ byteLength: mesh.byteLength }], bufferViews: [{ buffer: 0, byteOffset: 0, byteLength: mesh.byteLength }], accessors: [{ bufferView: 0, componentType: 5126, count: 3, type: 'VEC3', min: [0,0,0], max: [1,1,1] }], meshes: [{ primitives: [{ attributes: { POSITION: 0 } }] }], nodes: [{ mesh: 0 }], scenes: [{ nodes: [0] }], scene: 0 };
  const raw = JSON.stringify(metadata), json = Buffer.from(raw.padEnd(Math.ceil(raw.length/4)*4, ' '));
  const glb = Buffer.alloc(28 + json.length + mesh.byteLength);
  glb.writeUInt32LE(0x46546c67,0); glb.writeUInt32LE(2,4); glb.writeUInt32LE(glb.length,8); glb.writeUInt32LE(json.length,12); glb.writeUInt32LE(0x4e4f534a,16); json.copy(glb,20);
  glb.writeUInt32LE(mesh.byteLength,20+json.length); glb.writeUInt32LE(0x004e4942,24+json.length); Buffer.from(mesh.buffer).copy(glb,28+json.length);
  await page.getByLabel('Import GLB', { exact: true }).setInputFiles({ name: 'test-model.glb', mimeType: 'model/gltf-binary', buffer: glb });
  await page.getByRole('button', { name: 'Place in 3D', exact: true }).click();
  await page.getByRole('button', { name: 'Close models', exact: true }).click();
  await page.waitForTimeout(1600);
  await page.reload();
  await page.getByRole('button', { name: 'Tools', exact: true }).waitFor();
  await page.waitForTimeout(1600);
  assert.equal(await page.locator('input[aria-label^="Name "]').first().inputValue(), 'Release test room');
  await page.getByRole('button', { name: '3D', exact: true }).click();
  await page.waitForTimeout(2000);
  assert((await page.locator('canvas').count()) >= 1);
  await page.getByRole('button', { name: 'File', exact: true }).click();
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: /^Save\s*Ctrl/ }).click();
  const download = await downloadPromise;
  assert(download.suggestedFilename().endsWith('.floorplan3d'));
  const clean = await browser.newContext(); const reopened = await clean.newPage();
  await reopened.goto(process.env.PREVIEW_ORIGIN || 'http://127.0.0.1:4176/planner-test/');
  await reopened.getByRole('button', { name: 'File', exact: true }).waitFor();
  await reopened.locator('input[accept^=".floorplan3d"]').setInputFiles({ name: download.suggestedFilename(), mimeType: 'application/zip', buffer: await readFile(await download.path()) });
  await reopened.waitForTimeout(2000);
  assert.equal(await reopened.locator('input[aria-label^="Name "]').first().inputValue(), 'Release test room');
  await reopened.getByRole('button', { name: 'Tools', exact: true }).click();
  await reopened.getByRole('button', { name: 'My 3D models…', exact: true }).click();
  assert.equal(await reopened.getByRole('button', { name: 'Remove placement', exact: true }).count(), 1);
  await clean.close();
  assert.equal(events.filter(e => e.event === 'floorplan_created').length, 1);
  assert.equal(events.filter(e => e.event === 'floorplan_exported').length, 1);
  assert.equal(events.filter(e => e.event === 'floorplan_saved').length, 1);
  for (const event of events) assert.deepEqual(Object.keys(event.properties).sort(), ['$geoip_disable', '$process_person_profile', 'distinct_id', ...(event.event === 'floorplan_exported' ? ['format'] : [])].sort());
  await page.unroute('https://us.i.posthog.com/**');
  await page.route('https://us.i.posthog.com/**', route => route.abort());
  await page.getByRole('button', { name: 'File', exact: true }).click();
  const offlineDownload = page.waitForEvent('download'); await page.getByRole('button', { name: /^Save\s*Ctrl/ }).click(); await offlineDownload;
  await page.getByRole('button', { name: '2D', exact: true }).click();
  await page.waitForTimeout(1800);
  console.log('Buttons:', await page.getByRole('button').allTextContents());
  console.log('Status:', await page.getByRole('status').allTextContents());
  console.log('Errors:', errors); console.log('Failed requests:', failed);
  await mkdir('../.local-logs', { recursive: true });
  await page.screenshot({ path: '../.local-logs/shipping-desktop.png' });
  assert.equal(errors.length, 0, errors.join('\n'));
  const size = await page.locator('.planner-workspace').boundingBox(); assert.equal(size.height, 1000);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: '../.local-logs/shipping-mobile.png' });
  assert.equal((await page.locator('.planner-workspace').boundingBox()).height, 844);
  console.log('Public menu, local recovery, GLB placement, clean-browser package import, analytics counts/failure, and viewport checks passed.');
} finally { await browser.close(); }
